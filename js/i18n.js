function toCyr(text) {
  return String(text).split(KEEP_LATIN).map((part, i) => {
    if (i % 2) return part;   // защищённый фрагмент
    let out = "", low = part.toLowerCase();
    for (let j = 0; j < part.length;) {
      const pair = CYR_PAIRS.find(([k]) => low.startsWith(k, j));
      let ch, len;
      if (pair) { ch = pair[1]; len = pair[0].length; }
      else { ch = CYR_ONE[low[j]] ?? part[j]; len = 1; }
      // «e» в начале слова или после гласной — «э»
      if (low[j] === "e" && !pair && (j === 0 || !/[a-zа-яёўқғҳ]/i.test(low[j - 1]))) ch = "э";
      const upper = part[j] !== low[j];
      const upperNext = len > 1 && part[j + 1] && part[j + 1] !== low[j + 1];
      out += upper ? (upperNext || len === 1 ? ch.toUpperCase() : ch.charAt(0).toUpperCase() + ch.slice(1)) : ch;
      j += len;
    }
    return out;
  }).join("");
}
