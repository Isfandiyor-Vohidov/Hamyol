function t(key, vars) {
  const row = DICT[key];
  let s = row ? L3(row, typeof X_UI !== "undefined" ? X_UI[key] : null) : key;
  if (vars) for (const k in vars) s = s.replaceAll("{" + k + "}", vars[k]);
  return s;
}
